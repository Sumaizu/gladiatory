function node(tag, className, parts) {
  const item = document.createElement(tag);
  if (className) item.className = className;
  for (const part of parts || []) {
    if (typeof part === 'string') item.append(part);
    else if (part.b) item.append(node('b', '', [part.b]));
    else item.append(node('code', '', [part.code]));
  }
  return item;
}

export function renderRules(box) {
  box.textContent = '';
  for (const section of RULES) {
    if (section.lead) box.append(node('p', 'lead', section.lead));
    if (section.title) box.append(node('h3', '', [section.title]));
    if (section.text) box.append(node('p', '', section.text));
    for (const [key, tag] of [['list', 'ul'], ['steps', 'ol']]) {
      if (!section[key]) continue;
      const list = node(tag);
      for (const parts of section[key]) list.append(node('li', '', parts));
      box.append(list);
    }
    if (section.commands) {
      const list = node('dl', 'rules-commands');
      for (const [command, parts] of section.commands) list.append(node('dt', '', [c(command)]), node('dd', '', parts));
      box.append(list);
    }
    if (section.note) box.append(node('p', 'note-line', section.note));
  }
}
